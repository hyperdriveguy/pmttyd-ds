#!/usr/bin/env python3
"""Compile complete pinned original map material/light bodies; no runtime decoder."""
import argparse,hashlib,json,re,struct
from pathlib import Path
from compile_mario_constructor import compile_instruction,signed
from field_map_npc_assets import Dol
from iso_assets import DEFAULT_ISO
ROOT=Path(__file__).resolve().parents[1]
def instruction(address,w,internal):
 op=w>>26;d=(w>>21)&31;a=(w>>16)&31;b=(w>>11)&31
 ae=(f'r[{a}]+' if a else '')+f'uint32_t({signed(w&65535,16)})'
 advance=f'c.pc=0x{address+4:08x};break;'
 if op in (46,47):
  action=f'if(!word(({ae})+4*c.step,r[index]))return {{}};' if op==46 else f'if(!store(({ae})+4*c.step,r[index]))return {{}};'
  return f'while(c.step<{32-d}){{const auto index={d}+c.step;{action}++c.step;}}c.step=0;'+advance
 if op==48:return f'uint32_t value;if(!word({ae},value))return {{}};f[{d}]=realBits(double(scalar(value)));'+advance
 if op==52:return f'if(!store({ae},bits(float(real(f[{d}])))))return {{}};'+advance
 if op==50:return f'if(!c.step){{if(!word({ae},c.transfer))return {{}};c.step=1;}}uint32_t low;if(!word(({ae})+4,low))return {{}};f[{d}]=uint64_t(c.transfer)<<32|low;c.step=0;'+advance
 if op==54:return f'while(c.step<2){{if(!store(({ae})+4*c.step,uint32_t(f[{d}]>>(c.step?0:32))))return {{}};++c.step;}}c.step=0;'+advance
 if op in (56,60):
  displacement=signed(w&4095,12)
  if (w>>12)&15:raise ValueError('Not an unquantized two-lane private save')
  target=f'r[{a}]+uint32_t({displacement})'
  if op==60:return f'while(c.step<2){{if(!store(({target})+4*c.step,c.step?c.paired[{d}]:bits(float(real(f[{d}])))))return {{}};++c.step;}}c.step=0;'+advance
  return f'if(!c.step){{uint32_t value;if(!word({target},value))return {{}};f[{d}]=realBits(double(scalar(value)));c.step=1;}}if(!word(({target})+4,c.paired[{d}]))return {{}};c.step=0;'+advance
 if op in (59,63):
  xo=(w>>1)&1023;low=(w>>1)&31
  if op==63 and xo==72:return f'f[{d}]=f[{b}];'+advance
  if op==63 and xo in (0,32):
   i=((w>>23)&7)*4
   return f'const auto x=real(f[{a}]),y=real(f[{b}]);c.condition[{i}]=x<y;c.condition[{i+1}]=x>y;c.condition[{i+2}]=x==y;c.condition[{i+3}]=std::isnan(x)||std::isnan(y);'+advance
  if low in (20,25):
   value=f'real(f[{a}])-real(f[{b}])' if low==20 else f'real(f[{a}])*real(f[{(w>>6)&31}])'
   value=f'double(float({value}))' if op==59 else value
   return f'f[{d}]=realBits({value});'+advance
 if op==31:
  xo=(w>>1)&1023;record=f'compare(c,0,signedWord(r[{a}]),0);' if w&1 else ''
  if xo==40:return f'r[{d}]=r[{b}]-r[{a}];'+(f'compare(c,0,signedWord(r[{d}]),0);' if w&1 else '')+advance
  if xo==104:return f'r[{d}]=0u-r[{a}];'+(f'compare(c,0,signedWord(r[{d}]),0);' if w&1 else '')+advance
  if xo in (28,60):return f'r[{a}]=r[{d}]&'+('~' if xo==60 else '')+f'r[{b}];'+record+advance
  if xo==24:return f'r[{a}]=(r[{b}]&32)?0u:r[{d}]<<(r[{b}]&31);'+record+advance
 return compile_instruction(address,w,internal)
def generate(iso=DEFAULT_ISO):
 bodies=json.loads((ROOT/'tools/map_material_bodies.json').read_text())['bodies']
 internal={int(b['address'],16) for b in bodies}
 # Exact already-verified integer sort continuations; avoid a second translator
 # for their byte/scratch/recursive algorithm. Recheck every original word below.
 old=(ROOT/'source/field/field_map_source_program.inc').read_text()
 cases={int(a,16):(line,int(w,16)) for line,a,w in re.findall(r'^(case 0x([0-9a-f]{8}):.* // ([0-9a-f]{8}).*)$',old,re.M)}
 dol=Dol(iso);out=['// Complete original US map material/light continuation graph.','// Generated by tools/compile_map_material.py; --check verifies original bytes and translation.']
 try:
  for body in bodies:
   a=int(body['address'],16);raw=dol.read(a,body['size']);sha=hashlib.sha256(raw).hexdigest()
   if sha!=body['sha256']:raise ValueError('Changed original full body')
   out.append(f'// {body["name"]} {a:08x}/{len(raw):x} SHA256 {sha}')
   for offset in range(0,len(raw),4):
    at=a+offset;w=struct.unpack_from('>I',raw,offset)[0]
    if body['name'] in ('qqsort','fsort'):
     line,pinned=cases[at]
     if pinned!=w:raise ValueError('Changed shared sort source word')
     out.append(line)
    else:out.append(f'case 0x{at:08x}:{{{instruction(at,w,internal)}}} // {w:08x}')
 finally:dol.close()
 return '\n'.join(out)+'\n'
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--iso',default=DEFAULT_ISO);p.add_argument('--check',action='store_true');p.add_argument('--output',type=Path);args=p.parse_args();data=generate(args.iso)
 if args.check:
  if (ROOT/'source/display/source_map_material_program.inc').read_text()!=data:raise SystemExit('Compiled source graph differs')
  print('Verified',data.count('case 0x'),'original map material/light instructions')
 elif args.output:
  if args.output.exists():raise SystemExit('Output must be absent')
  args.output.write_text(data)
 else:p.error('--check or --output required')
