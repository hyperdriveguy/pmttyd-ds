def verify(iso):
    with Path(iso).open('rb') as disc:
        if disc.read(8)!=b'G8ME01\0\0':
            raise ValueError('Expected US G8ME01 disc0 revision0')
        disc.seek(0x420)
        dol_offset=struct.unpack('>I',disc.read(4))[0]
        disc.seek(dol_offset)
        header=disc.read(256)
        def read(address,size):
            matches=[]
            for i in range(18):
                off,va,length=(struct.unpack_from('>I',header,j+i*4)[0] for j in (0,0x48,0x90))
                if va<=address and address+size<=va+length:
                    matches.append(dol_offset+off+address-va)
            if len(matches)!=1:
                raise ValueError(f'Unmapped/ambiguous DOL address {address:#x}')
            disc.seek(matches[0]);data=disc.read(size)
            if len(data)!=size:
                raise ValueError('Truncated DOL')
            return data
        def normalized(address,size):
            result=[]
            for i in range(0,size,4):
                at=address+i
                word=struct.unpack('>I',read(at,4))[0]
                if word>>26==18 and word&1:
                    delta=word&0x3fffffc
                    if delta&0x2000000: delta-=0x4000000
                    result.append(('call',(delta if word&2 else at+delta)&0xffffffff))
                elif i in (8,24) or word&0xffff0000==0x389e0000:
                    result.append(('source',word&0xffff0000))
                else:
                    result.append(('instruction',word))
            return result
        ref=BODIES['unit_party_christine.o::__makeTechMenuFunc']
        expected=normalized(ref[0],ref[1])
        for ns in ('clauda','yoshi','chuchurina','sanders','vivian'):
            body=BODIES[f'unit_party_{ns}.o::__makeTechMenuFunc']
            if normalized(body[0],body[1])!=expected:
                raise ValueError(f'Full normalized callback pattern mismatch: {ns}')
        for name,(address,size,digest) in BODIES.items():
            if hashlib.sha256(read(address,size)).hexdigest()!=digest:
                raise ValueError(f'Body mismatch: {name}')
        for address,value in {**ANCHORS,**CONSTANTS}.items():
            if read(address,len(value)//2).hex()!=value:
                raise ValueError(f'Instruction/constant mismatch: {address:#x}')
    return dict(schema=1,scope='All seven complete party weapon callbacks and tech-level query;source heads keys and seven key1 chains pinned;unit provisioning/event/query/Game/runtime remain open',normalized_complete_callbacks=5,bodies=len(BODIES),instruction_anchors=len(ANCHORS),data_spans=len(CONSTANTS))


