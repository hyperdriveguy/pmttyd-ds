def verify(iso=DEFAULT_ISO):
    with Path(iso).open('rb') as disc:
        if disc.read(8) != b'G8ME01\0\0':
            raise ValueError('Original US G8ME01 disc0 revision0 required')
        disc.seek(0x420)
        dol = struct.unpack('>I', disc.read(4))[0]
        disc.seek(dol)
        header = disc.read(256)
        sections = [tuple(struct.unpack_from('>I', header, b + 4*i)[0]
                          for b in (0, 0x48, 0x90)) for i in range(18)]

        def read(address, size):
            offsets = [off + address - va for off, va, n in sections
                       if off and va <= address and address + size <= va + n]
            if len(offsets) != 1:
                raise ValueError('Ambiguous/unmapped original source span')
            disc.seek(dol + offsets[0])
            raw = disc.read(size)
            if len(raw) != size:
                raise ValueError('Truncated original source')
            return raw

        for name, expected in EVIDENCE['bodies'].items():
            address, size = expected['address'], expected['size']
            raw = read(address, size)
            if hashlib.sha256(raw).hexdigest() != expected['sha256']:
                raise ValueError('Original body changed: ' + name)
            calls = []
            for i in range(0, size, 4):
                word = struct.unpack_from('>I', raw, i)[0]
                if word & 0xfc000003 == 0x48000001:
                    relative = word & 0x03fffffc
                    if relative & 0x02000000:
                        relative -= 0x04000000
                    calls.append([address+i, (address+i+relative) & 0xffffffff])
            if calls != expected['calls']:
                raise ValueError('Original complete callsite list changed: ' + name)
        if list(struct.unpack('>15I', read(EVIDENCE['dispatch_address'], 60))) != EVIDENCE['dispatch']:
            raise ValueError('Original Act dispatch changed')
        if read(EVIDENCE['camera_constant_address'], 4).hex() != EVIDENCE['camera_constant_hex']:
            raise ValueError('Original camera comparison constant changed')
    implementation = (Path(__file__).resolve().parents[1] /
                      'source/battle/battle_act_continuation.cpp').read_text()
    cases = {int(n, 16) for n in re.findall(r'case (0x[0-9a-f]+)', implementation)}
    inline_sequences = {0x800f89a0, 0x800f8a08, 0x800f895c}
    children = [site for site, function in EVIDENCE['bodies']['btlseqAct']['calls']
                if function not in inline_sequences]
    if len(children) != 64 or any(site not in cases for site in children):
        raise ValueError('Act owner lost an explicit original child resume boundary')
    return dict(bodies=len(EVIDENCE['bodies']), act_instructions=555,
                act_callsites=len(EVIDENCE['bodies']['btlseqAct']['calls']),
                retained_child_callsites=len(children),
                dispatch_entries=15, physical_audience_callers=3,
                limitation='Static source pins; no executed-original or native gameplay claim')


